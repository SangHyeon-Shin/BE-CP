#!/usr/bin/env python3
"""Claude Code 원본(.claude/)에서 Codex용 파일을 만든다.

원본(직접 고치는 곳)           →  생성물(직접 고치지 않음)
  .claude/skills/<이름>/          →  .agents/skills/<이름>/            Codex 스킬
  .claude/commands/<이름>.md      →  .agents/skills/<이름>/SKILL.md    명령을 스킬로
  .claude/agents/<이름>.md        →  .codex/agents/<이름_밑줄>.toml    하위 에이전트

Codex 규칙에 맞춰 바꾸는 것:
  - SKILL.md frontmatter는 name, description 두 개만 남긴다.
  - description은 1,024자 이하로 문장 단위로 줄인다.
  - Claude의 $ARGUMENTS 자리는 "사용자가 요청에서 지정한 값"으로 바꾼다.
  - disable-model-invocation: true 인 스킬은 agents/openai.yaml로 자동 호출을 끈다.

실행:  python tools/sync_codex.py          생성물 갱신
       python tools/sync_codex.py --check  원본과 생성물이 맞는지만 확인(다르면 종료 코드 1)
"""
from __future__ import annotations

import filecmp
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_SKILLS = ROOT / ".claude" / "skills"
SRC_COMMANDS = ROOT / ".claude" / "commands"
SRC_AGENTS = ROOT / ".claude" / "agents"
OUT_SKILLS = Path(".agents") / "skills"
OUT_AGENTS = Path(".codex") / "agents"
DESC_MAX = 1024
ARG_TEXT = "(사용자가 요청에서 지정한 파일·값)"
MARKER = "<!-- generated by tools/sync_codex.py from .claude/ ; edit the source, not this file -->\n"

FM_RE = re.compile(r"^---\n(.*?)\n---\n?", re.S)


def split_frontmatter(text: str) -> tuple[dict, str]:
    m = FM_RE.match(text)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        km = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if km:
            value = km.group(2).strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1].replace('\\"', '"')
            meta[km.group(1)] = value
    return meta, text[m.end():]


def shorten(desc: str) -> str:
    desc = " ".join(desc.split())
    if len(desc) <= DESC_MAX:
        return desc
    out = ""
    for sentence in re.split(r"(?<=[.!?])\s+", desc):
        if len(out) + len(sentence) + 1 > DESC_MAX:
            break
        out = (out + " " + sentence).strip()
    return out or desc[:DESC_MAX - 1] + "…"


def skill_md(name: str, desc: str, body: str) -> str:
    body = body.replace("$ARGUMENTS", ARG_TEXT).lstrip("\n")
    return (f"---\nname: {name}\ndescription: {json.dumps(shorten(desc), ensure_ascii=False)}\n---\n"
            f"{MARKER}\n{body}")


def toml_multiline(text: str) -> str:
    return '"""\n' + text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '"""'


def build(out_root: Path) -> list[str]:
    notes = []
    skills_dir = out_root / OUT_SKILLS
    agents_dir = out_root / OUT_AGENTS
    skills_dir.mkdir(parents=True, exist_ok=True)
    agents_dir.mkdir(parents=True, exist_ok=True)

    # 1) skills
    for src in sorted(p for p in SRC_SKILLS.iterdir() if (p / "SKILL.md").is_file()):
        dst = skills_dir / src.name
        shutil.copytree(src, dst)
        meta, body = split_frontmatter((src / "SKILL.md").read_text("utf-8"))
        desc = meta.get("description") or meta.get("summary") or src.name
        if len(" ".join(desc.split())) > DESC_MAX:
            notes.append(f"skill {src.name}: description shortened to {DESC_MAX} chars")
        (dst / "SKILL.md").write_text(skill_md(src.name, desc, body), "utf-8")
        if meta.get("disable-model-invocation", "").lower() == "true":
            (dst / "agents").mkdir(exist_ok=True)
            (dst / "agents" / "openai.yaml").write_text(
                "policy:\n  allow_implicit_invocation: false\n", "utf-8")

    # 2) commands -> skills
    for src in sorted(SRC_COMMANDS.glob("*.md")):
        name = src.stem
        if (skills_dir / name).exists():
            notes.append(f"command {name}: a skill with this name exists, skipped")
            continue
        meta, body = split_frontmatter(src.read_text("utf-8"))
        desc = meta.get("description") or meta.get("summary") or name
        hint = meta.get("argument-hint", "")
        head = ("이 스킬은 Claude Code 명령을 옮긴 것이다. 입력은 사용자가 요청과 함께 준 내용이다"
                + (f"(형식: {hint})" if hint else "") + ".\n\n")
        (skills_dir / name).mkdir()
        (skills_dir / name / "SKILL.md").write_text(skill_md(name, desc, head + body), "utf-8")

    # 3) agents -> Codex custom agents
    for src in sorted(SRC_AGENTS.glob("*.md")):
        meta, body = split_frontmatter(src.read_text("utf-8"))
        name = src.stem.replace("-", "_")
        desc = shorten(meta.get("description") or meta.get("summary") or name)
        text = ("# generated by tools/sync_codex.py from .claude/agents/" + src.name +
                " ; edit the source, not this file\n"
                f"name = {json.dumps(name, ensure_ascii=False)}\n"
                f"description = {json.dumps(desc, ensure_ascii=False)}\n"
                f"developer_instructions = {toml_multiline(body.strip())}\n")
        (agents_dir / f"{name}.toml").write_text(text, "utf-8")
    return notes


def tree_equal(a: Path, b: Path) -> bool:
    if not a.exists() or not b.exists():
        return a.exists() == b.exists()
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(tree_equal(a / d, b / d) for d in cmp.common_dirs)


def main() -> int:
    check = "--check" in sys.argv
    with tempfile.TemporaryDirectory() as tmp:
        tmp_root = Path(tmp)
        notes = build(tmp_root)
        if tomllib_check(tmp_root) is False:
            return 2
        if check:
            same = all(tree_equal(tmp_root / rel, ROOT / rel) for rel in (OUT_SKILLS, OUT_AGENTS))
            print("Codex 파일이 원본과 일치합니다." if same else
                  "Codex 파일이 원본(.claude/)과 다릅니다. python tools/sync_codex.py 를 실행하세요.")
            return 0 if same else 1
        for rel in (OUT_SKILLS, OUT_AGENTS):
            target = ROOT / rel
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(tmp_root / rel, target)
    n_sk = len(list((ROOT / OUT_SKILLS).iterdir()))
    n_ag = len(list((ROOT / OUT_AGENTS).glob("*.toml")))
    print(f"생성 완료: .agents/skills {n_sk}개, .codex/agents {n_ag}개")
    for note in notes:
        print("  - " + note)
    return 0


def tomllib_check(root: Path):
    try:
        import tomllib
    except ImportError:  # Python < 3.11: skip validation
        return None
    for path in (root / OUT_AGENTS).glob("*.toml"):
        try:
            data = tomllib.loads(path.read_text("utf-8"))
        except Exception as error:
            print(f"오류: {path.name} TOML 형식 오류: {error}")
            return False
        for key in ("name", "description", "developer_instructions"):
            if not data.get(key):
                print(f"오류: {path.name}에 {key}가 없습니다.")
                return False
    return True


if __name__ == "__main__":
    sys.exit(main())
